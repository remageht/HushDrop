package app.hushdrop.host

import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.ByteArrayInputStream
import java.io.ByteArrayOutputStream
import java.io.File
import java.io.IOException
import java.nio.file.Files
import java.security.SecureRandom

/**
 * JVM tests of the V2 at-rest container (mirrors internal/crypto/atrest_test.go).
 * Pure java.io/javax.crypto — no Robolectric needed.
 */
class AtRestCryptoTest {

    private fun freshKey(): ByteArray = ByteArray(AtRestCrypto.KEY_SIZE).also { SecureRandom().nextBytes(it) }

    private fun encryptToBytes(data: ByteArray, key: ByteArray): ByteArray {
        val out = ByteArrayOutputStream()
        AtRestCrypto.encryptStream(ByteArrayInputStream(data), out, key)
        return out.toByteArray()
    }

    private fun decryptToBytes(container: ByteArray, key: ByteArray): ByteArray {
        val out = ByteArrayOutputStream()
        AtRestCrypto.decryptStream(ByteArrayInputStream(container), out, key)
        return out.toByteArray()
    }

    private fun hex(s: String): ByteArray {
        require(s.length % 2 == 0)
        return ByteArray(s.length / 2) { i ->
            ((Character.digit(s[i * 2], 16) shl 4) or Character.digit(s[i * 2 + 1], 16)).toByte()
        }
    }

    private fun hexOf(b: ByteArray): String = b.joinToString("") { String.format("%02x", it) }

    private fun expectedSize(plaintext: Long): Long {
        val frames = if (plaintext > 0) (plaintext + AtRestCrypto.SEGMENT_SIZE - 1) / AtRestCrypto.SEGMENT_SIZE else 0L
        return 28L + frames * 20L + 20L + plaintext
    }

    @Test
    fun roundtripAcrossSizes() {
        val sizes = longArrayOf(
            0L, 1L, 100L,
            AtRestCrypto.SEGMENT_SIZE.toLong(),
            AtRestCrypto.SEGMENT_SIZE.toLong() + 1L,
            9L * 1024 * 1024
        )
        val key = freshKey()
        for (size in sizes) {
            val data = ByteArray(size.toInt()).also { SecureRandom().nextBytes(it) }
            val container = encryptToBytes(data, key)

            assertEquals(expectedSize(size), container.size.toLong())

            // The plaintext (first 64 random bytes) must not appear anywhere. The check
            // only makes sense when the probe is long enough not to match by chance.
            if (size >= 64) {
                val latin = String(container, Charsets.ISO_8859_1)
                val probe = data.copyOfRange(0, 64)
                assertFalse(
                    "plaintext leaked into container (size=$size)",
                    latin.contains(String(probe, Charsets.ISO_8859_1))
                )
            }

            val decrypted = decryptToBytes(container, key)
            assertArrayEquals("roundtrip mismatch (size=$size)", data, decrypted)
        }
    }

    @Test
    fun scatteredSmallWritesProduceSameFraming() {
        val data = ByteArray(0x7FA13).also { SecureRandom().nextBytes(it) }
        val key = freshKey()

        val single = encryptToBytes(data, key)
        val scattered = ByteArrayOutputStream()
        val w = AtRestCrypto.encryptingOutputStream(scattered, key)
        var pos = 0
        var chunk = 1
        while (pos < data.size) {
            val take = minOf(1 + (chunk * 7) % 43, data.size - pos)
            w.write(data, pos, take)
            pos += take
            chunk++
        }
        w.close()

        assertEquals(single.size, scattered.size())
    }

    @Test
    fun knownGoVectorDecrypts() {
        // Vector generated by the Go implementation: key 0x00..0x1f,
        // plaintext "HushDrop cross-language at-rest vector: Go writes, Kotlin must read."
        val goContainerHex =
            "4855534844524f505f454e435f56320ae00328a759706ab70040000000000044" +
                    "729297cf7d01d7431f1a01141dcab4737df6666b9109706a66ede935a2a78e99" +
                    "5d1bc3c490256ff220349ec95aa6ee1bb55dc1e6f79ae7fa777e8fdb3ac91cd" +
                    "647f53502137abb1baed6ca01a1591e8ba0320a8900000000f231f1af91f0ad" +
                    "1957235e2b91680a98"
        val container = hex(goContainerHex)
        assertEquals(136, container.size)

        val key = ByteArray(32) { it.toByte() }
        val plain = "HushDrop cross-language at-rest vector: Go writes, Kotlin must read."
        val decrypted = decryptToBytes(container, key)
        assertEquals(plain, String(decrypted, Charsets.UTF_8))
    }

    @Test
    fun wrongKeyFailsWithoutPlaintext() {
        val data = "Sensitive HushDrop message to be encrypted at rest".toByteArray(Charsets.UTF_8)
        val container = encryptToBytes(data, freshKey())

        val out = ByteArrayOutputStream()
        try {
            AtRestCrypto.decryptStream(ByteArrayInputStream(container), out, freshKey())
            throw AssertionError("expected decryption to fail with a foreign key")
        } catch (_: AtRestCrypto.AtRestInvalidKeyException) {
            // expected
        }
        assertEquals(0, out.size())
    }

    @Test
    fun corruptedContainerSubsets() {
        val data = "Sensitive HushDrop payload that will have bytes corrupted".toByteArray(Charsets.UTF_8)
        val key = freshKey()
        val container = encryptToBytes(data, key)
        // Layout: magic(16) base(8) segLen(4)=28, then frame len prefix at 28, body at 32.
        val firstFrameBody = 28 + 4

        // payload byte flip → authentication failure
        var corrupted = container.clone()
        corrupted[firstFrameBody] = (corrupted[firstFrameBody].toInt() xor 0xFF).toByte()
        try {
            decryptToBytes(corrupted, key); throw AssertionError("payload corruption must fail")
        } catch (_: AtRestCrypto.AtRestInvalidKeyException) {}

        // eof tag byte flip → authentication failure
        corrupted = container.clone()
        corrupted[corrupted.size - 1] = (corrupted[corrupted.size - 1].toInt() xor 0xAA).toByte()
        try {
            decryptToBytes(corrupted, key); throw AssertionError("eof tag corruption must fail")
        } catch (_: AtRestCrypto.AtRestInvalidKeyException) {}

        // base nonce flip → authentication failure
        corrupted = container.clone()
        corrupted[16] = (corrupted[16].toInt() xor 0x55).toByte()
        try {
            decryptToBytes(corrupted, key); throw AssertionError("base nonce corruption must fail")
        } catch (_: AtRestCrypto.AtRestInvalidKeyException) {}

        // jumbo frame length prefix → structural failure
        corrupted = container.clone()
        AtRestCrypto.putBe32(corrupted, 28, 0xFFFFFFFFL)
        try {
            decryptToBytes(corrupted, key); throw AssertionError("jumbo length must fail")
        } catch (_: AtRestCrypto.AtRestCorruptFrameException) {}

        // truncated mid-frame → structural failure
        try {
            decryptToBytes(container.copyOfRange(0, container.size - 24), key)
            throw AssertionError("truncation must fail")
        } catch (_: AtRestCrypto.AtRestCorruptFrameException) {}

        // missing eof frame → structural failure
        try {
            decryptToBytes(container.copyOfRange(0, container.size - 20), key)
            throw AssertionError("missing eof must fail")
        } catch (_: AtRestCrypto.AtRestCorruptFrameException) {}

        // trailing junk after eof → structural failure
        corrupted = container.clone() + 0
        try {
            decryptToBytes(corrupted, key); throw AssertionError("trailing junk must fail")
        } catch (_: AtRestCrypto.AtRestCorruptFrameException) {}
    }

    @Test
    fun invalidHeaderRejected() {
        val junk = ByteArray(40).also { SecureRandom().nextBytes(it) }
        try {
            decryptToBytes(junk, freshKey()); throw AssertionError("random bytes must not decrypt")
        } catch (_: AtRestCrypto.AtRestInvalidHeaderException) {}

        try {
            decryptToBytes(ByteArray(10), freshKey())
            throw AssertionError("short stream must fail with header error")
        } catch (_: AtRestCrypto.AtRestInvalidHeaderException) {}
    }

    @Test
    fun badKeyLengthRejected() {
        // Writer path
        try {
            encryptToBytes("test data".toByteArray(), ByteArray(16))
            throw AssertionError("short key must be rejected by the writer")
        } catch (_: AtRestCrypto.AtRestInvalidKeyException) {}

        // Reader path
        try {
            AtRestCrypto.decryptingInputStream(ByteArrayInputStream(ByteArray(0)), ByteArray(8))
            throw AssertionError("short key must be rejected by the reader")
        } catch (_: AtRestCrypto.AtRestInvalidKeyException) {}
    }

    @Test
    fun keyFileLifecycle() {
        val dir = Files.createTempDirectory("atrestkey").toFile()
        dir.deleteOnExit()
        val keyFile = File(dir, "nested/${AtRestCrypto.KEY_FILE_NAME}")

        val key1 = AtRestCrypto.loadOrCreateAtRestKey(keyFile)
        assertEquals(AtRestCrypto.KEY_SIZE, key1.size)

        val key2 = AtRestCrypto.loadOrCreateAtRestKey(keyFile)
        assertArrayEquals(key1, key2)

        // Wrong-size key file must be rejected instead of silently used.
        keyFile.writeBytes(ByteArray(8))
        try {
            AtRestCrypto.loadOrCreateAtRestKey(keyFile)
            throw AssertionError("wrong-size key file must be rejected")
        } catch (_: AtRestCrypto.AtRestInvalidKeyException) {}
    }

    @Test
    fun writerLifecycle() {
        val key = freshKey()

        val out = ByteArrayOutputStream()
        val w = AtRestCrypto.encryptingOutputStream(out, key)
        w.write("hello".toByteArray(Charsets.US_ASCII))
        w.close()
        w.close() // idempotent
        try {
            w.write("more".toByteArray(Charsets.US_ASCII))
            throw AssertionError("write after close must fail")
        } catch (_: AtRestCrypto.AtRestWriteAfterCloseException) {}

        // Empty container has exactly the header + eof framing.
        val emptyOut = ByteArrayOutputStream()
        val ew = AtRestCrypto.encryptingOutputStream(emptyOut, key)
        ew.close()
        assertEquals(48L, emptyOut.size().toLong())
        val plain = decryptToBytes(emptyOut.toByteArray(), key)
        assertEquals(0, plain.size)
    }

    @Test
    fun isEncryptedPrefixCheck() {
        val dir = Files.createTempDirectory("atrestenc").toFile()
        dir.deleteOnExit()

        val containerFile = File(dir, "c.bin")
        containerFile.writeBytes(encryptToBytes("payload".toByteArray(), freshKey()))
        assertTrue(AtRestCrypto.isEncrypted(containerFile))

        val plainFile = File(dir, "p.txt")
        plainFile.writeText("plain text without hushdrop header", Charsets.UTF_8)
        assertFalse(AtRestCrypto.isEncrypted(plainFile))

        val shortFile = File(dir, "s.bin")
        shortFile.writeBytes(byteArrayOf(0x48, 0x55))
        assertFalse(AtRestCrypto.isEncrypted(shortFile))

        assertFalse(AtRestCrypto.isEncrypted(File(dir, "missing.bin")))
    }

    @Test
    fun magicAndNonceLayoutIsFixed() {
        assertEquals("HUSHDROP_ENC_V2\n", String(AtRestCrypto.MAGIC_BYTES, Charsets.US_ASCII))
        assertEquals(16, AtRestCrypto.MAGIC_BYTES.size)
        assertEquals(12, AtRestCrypto.GCM_NONCE_SIZE)
        val nonce = AtRestCrypto.frameNonce(ByteArray(8) { it.toByte() }, 1L)
        assertEquals(12, nonce.size)
        for (i in 0 until 8) assertEquals(i.toByte(), nonce[i])
        assertEquals(0, nonce[8].toInt() and 0xFF)
        assertEquals(0, nonce[9].toInt() and 0xFF)
        assertEquals(0, nonce[10].toInt() and 0xFF)
        assertEquals(1, nonce[11].toInt() and 0xFF)
    }
}
